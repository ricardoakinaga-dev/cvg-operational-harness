#!/usr/bin/env node
// Node 22.23+ native type stripping; no workspace build or installed package needed.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { canonicalizeJson } from '../packages/contracts/src/canonical-json.ts'

const schemaPath = new URL(
  '../packages/contracts/src/session-event-schemas.v1.json',
  import.meta.url
)
const outputPath = new URL(
  '../docs/architecture/SESSION_EVENT_CATALOG.md',
  import.meta.url
)
const catalog = JSON.parse(readFileSync(schemaPath, 'utf8'))
if (
  catalog.formatVersion !== 1 ||
  !catalog.definitions ||
  !catalog.events ||
  !Object.keys(catalog.events).length
)
  throw new Error('Invalid session event catalog')
const rows = Object.keys(catalog.events)
  .sort()
  .map((type) => {
    const digest = createHash('sha256')
      .update(
        canonicalizeJson({
          formatVersion: 1,
          type,
          payload: catalog.events[type],
          definitions: catalog.definitions
        })
      )
      .digest('hex')
    return `| \`${type}\` | 1 | \`${digest}\` |`
  })
const text = [
  '<!-- GENERATED by scripts/gen-session-catalog.mjs; DO NOT EDIT BY HAND -->',
  '',
  '# Session Event Catalog',
  '',
  'Fingerprint: SHA-256 of canonical JSON `{ formatVersion, type, payload, definitions }` (shared-rfc8785-subset-v1).',
  '',
  '| type | formatVersion | schemaFingerprint |',
  '| --- | --- | --- |',
  ...rows,
  ''
].join('\n')
if (process.argv.includes('--check')) {
  let existing = ''
  try {
    existing = readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n')
  } catch {
    /* absent is drift */
  }
  if (existing !== text) {
    console.error(
      'SESSION_EVENT_CATALOG.md is stale; run npm run session-catalog'
    )
    process.exitCode = 1
  } else
    console.log(`Session event catalog up to date (${rows.length} event types)`)
} else {
  writeFileSync(outputPath, text)
  console.log(`wrote ${fileURLToPath(outputPath)} (${rows.length} event types)`)
}
