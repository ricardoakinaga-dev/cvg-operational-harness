#!/usr/bin/env node
/**
 * PDSH-014: generate docs/architecture/TOOL_CATALOG.md from the real tool
 * descriptors in packages/sandbox and the skills under skills/<id>/skill.json.
 *
 *   node scripts/gen-tool-catalog.mjs           # write the catalog
 *   node scripts/gen-tool-catalog.mjs --check   # drift-check (exit 1 on drift)
 *
 * Deterministic: same tree -> same bytes. No timestamps, no locale, sorted ids.
 */
import {
  readFileSync,
  readdirSync,
  writeFileSync,
  existsSync,
  statSync
} from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)))
const OUT_PATH = join(ROOT, 'docs', 'architecture', 'TOOL_CATALOG.md')
const SKILLS_DIR = join(ROOT, 'skills')
const TOOL_SOURCES = [
  join(ROOT, 'packages', 'sandbox', 'src', 'fs-tools.ts'),
  join(ROOT, 'packages', 'sandbox', 'src', 'shell-tool.ts'),
  join(ROOT, 'packages', 'channel-gateway', 'src', 'exam-egress.ts')
]

const HEADER =
  '<!-- GENERATED by scripts/gen-tool-catalog.mjs; DO NOT EDIT BY HAND -->'

/** Extract `field: 'literal'` or `field: true|false` from a TS source block. */
function extractField(block, field) {
  const stringMatch = block.match(new RegExp(`${field}:\\s*'([^']+)'`))
  if (stringMatch) return stringMatch[1]
  const boolMatch = block.match(new RegExp(`${field}:\\s*(true|false)`))
  if (boolMatch) return boolMatch[1]
  return undefined
}

/** Extract a description that may be inline or on the following line. */
function extractDescription(block) {
  const inline = block.match(/description:\s*'([^']+)'/)
  if (inline) return inline[1]
  const nextLine = block.match(/description:\s*\n\s*'([^']+)'/)
  if (nextLine) return nextLine[1]
  return undefined
}

/**
 * Parse one tool source file. Tools are object literals that start with
 * `id: '<tool-id>'` and carry descriptor fields; shared BASE fields
 * (version, requiresApproval) come from the nearest `const *_BASE` object.
 */
function parseToolFile(filePath) {
  const source = readFileSync(filePath, 'utf8')

  // Shared base: first `version: '...'` and `requiresApproval: true|false`.
  const baseVersion = source.match(/version:\s*'([^']+)'/)?.[1]
  const baseApproval = source.match(/requiresApproval:\s*(true|false)/)?.[1]
  if (!baseVersion || !baseApproval) {
    throw new Error(
      `${filePath}: could not extract shared BASE (version/requiresApproval)`
    )
  }

  // Split on tool object starts: lines with `id: '<id>',` at object scope.
  const tools = []
  const idRegex = /^\s*id:\s*'([a-z0-9.-]+)',\s*$/gm
  const idMatches = [...source.matchAll(idRegex)]
  for (let i = 0; i < idMatches.length; i += 1) {
    const id = idMatches[i][1]
    const start = idMatches[i].index
    const end =
      i + 1 < idMatches.length ? idMatches[i + 1].index : source.length
    const block = source.slice(start, end)
    const tool = {
      id,
      version: extractField(block, 'version') ?? baseVersion,
      description: extractDescription(block),
      risk: extractField(block, 'risk'),
      sideEffect: extractField(block, 'sideEffect'),
      idempotent: extractField(block, 'idempotent'),
      requiresApproval: extractField(block, 'requiresApproval') ?? baseApproval,
      sandbox: extractField(block, 'sandbox')
    }
    for (const [key, value] of Object.entries(tool)) {
      if (value === undefined) {
        throw new Error(
          `${filePath}: tool '${id}' missing descriptor field '${key}'`
        )
      }
    }
    tools.push(tool)
  }
  if (tools.length === 0) {
    throw new Error(`${filePath}: no tool descriptors found`)
  }
  return tools
}

/** Load and validate skills from the skills directory (PDSH-015 layout). */
function loadSkills() {
  if (!existsSync(SKILLS_DIR) || !statSync(SKILLS_DIR).isDirectory()) {
    throw new Error(`skills directory missing: ${SKILLS_DIR}`)
  }
  const skills = []
  for (const entry of readdirSync(SKILLS_DIR).sort()) {
    const dir = join(SKILLS_DIR, entry)
    if (!statSync(dir).isDirectory()) continue
    const manifestPath = join(dir, 'skill.json')
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
    if (manifest.id !== entry) {
      throw new Error(
        `skill id '${manifest.id}' does not match directory '${entry}'`
      )
    }
    skills.push({
      id: manifest.id,
      version: manifest.version,
      riskLevel: manifest.riskLevel,
      requiredTools: manifest.requiredTools,
      requiredKnowledge: manifest.requiredKnowledge,
      description: manifest.description
    })
  }
  return skills.sort((a, b) => a.id.localeCompare(b.id))
}

function renderCatalog(tools, skills) {
  const lines = [HEADER, '', '# Tool & Skill Catalog', '']
  lines.push('## Tools', '')
  lines.push(
    '| id | version | risk | sideEffect | idempotent | requiresApproval | sandbox | description |'
  )
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const tool of tools) {
    lines.push(
      `| \`${tool.id}\` | ${tool.version} | ${tool.risk} | ${tool.sideEffect} | ${tool.idempotent} | ${tool.requiresApproval} | ${tool.sandbox} | ${tool.description} |`
    )
  }
  lines.push('', '## Skills', '')
  lines.push(
    '| id | version | riskLevel | requiredTools | requiredKnowledge | description |'
  )
  lines.push('| --- | --- | --- | --- | --- | --- |')
  for (const skill of skills) {
    const toolsList =
      skill.requiredTools.map((t) => `\`${t}\``).join(', ') || '—'
    const knowledgeList =
      skill.requiredKnowledge.map((k) => `\`${k}\``).join(', ') || '—'
    lines.push(
      `| \`${skill.id}\` | ${skill.version} | ${skill.riskLevel} | ${toolsList} | ${knowledgeList} | ${skill.description} |`
    )
  }
  lines.push('')
  return lines.join('\n')
}

function main() {
  const check = process.argv.includes('--check')
  const tools = TOOL_SOURCES.flatMap(parseToolFile).sort((a, b) =>
    a.id.localeCompare(b.id)
  )
  const skills = loadSkills()
  const generated = renderCatalog(tools, skills)

  if (check) {
    if (!existsSync(OUT_PATH)) {
      console.error(`TOOL_CATALOG.md missing: ${OUT_PATH}`)
      process.exit(1)
    }
    const committed = readFileSync(OUT_PATH, 'utf8').replace(/\r\n/g, '\n')
    if (committed !== generated) {
      console.error(
        'TOOL_CATALOG.md is stale; run: node scripts/gen-tool-catalog.mjs'
      )
      process.exit(1)
    }
    console.log(
      `TOOL_CATALOG.md up to date (${tools.length} tools, ${skills.length} skills)`
    )
    return
  }

  writeFileSync(OUT_PATH, generated)
  console.log(
    `wrote ${OUT_PATH} (${tools.length} tools, ${skills.length} skills)`
  )
}

main()
